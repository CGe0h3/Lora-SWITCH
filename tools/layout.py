#!/usr/bin/env python3
"""
Single source of truth for the multi-boot flash layout (Heltec WiFi LoRa 32 V4, 16 MB).

Running this script regenerates:
  partitions/menu.csv              table used by the boot menu
  partitions/slot0.csv ... slotN   table each firmware "sees" when it runs
  common/multiboot_layout.h        constants shared by the bootloader hook and the menu

Physical map (16 MB):
  0x000000  bootloader (custom hook)
  0x008000  ACTIVE partition table  <- rewritten by the bootloader before each boot
  0x009000  nvs (menu)
  0x00E000  otadata (menu, always blank)
  0x010000  menu app (factory)                    448 KB
  0x080000  bootsel record                          4 KB
  0x081000  ptables store (menu + one per slot)   4 KB each
  0x090000  slot i private: nvs (48 KB) + otadata (8 KB), 64 KB per slot
  0x0C0000  slot i app image                       3 MB each
  0x9C0000  slot i filesystem                      ~2 MB each

Edit SLOTS below (names shown on the OLED, FS partition label each firmware expects),
then run:  python3 tools/layout.py
"""
import os

FLASH_SIZE = 16 * 1024 * 1024

# (name on screen (max 14 chars), label of the filesystem partition the firmware mounts,
#  declared filesystem size or None = whole area)
# Meshtastic, MeshCore and most Arduino firmwares mount the partition labelled "spiffs".
# RNode ships a SPIFFS image (web console) built for exactly 1920 KB.
SLOTS = [
    ("Meshtastic", "spiffs", None),
    ("MeshCore",   "spiffs", None),
    ("Reticulum",  "spiffs", 0x1E0000),
]

MENU_APP_OFF, MENU_APP_SIZE = 0x10000, 0x70000
BOOTSEL_OFF, BOOTSEL_SIZE = 0x80000, 0x1000
PTABLES_OFF = 0x81000
META_BASE, META_STRIDE = 0x90000, 0x10000
NVS_SIZE, OTADATA_SIZE = 0xC000, 0x2000
APP_BASE, APP_SIZE = 0xC0000, 0x300000

n = len(SLOTS)
assert 1 <= n <= 3, "the 16 MB layout is sized for up to 3 slots"
FS_BASE = APP_BASE + n * APP_SIZE
FS_SIZE = ((FLASH_SIZE - 0x10000 - FS_BASE) // n) & ~0xFFFF   # keep last 64 KB spare
PTABLES_SIZE = 0x1000 * (n + 1)
assert META_BASE + n * META_STRIDE <= APP_BASE
assert PTABLES_OFF + PTABLES_SIZE <= META_BASE
assert FS_BASE + n * FS_SIZE <= FLASH_SIZE


def slot(i):
    meta = META_BASE + i * META_STRIDE
    return dict(nvs=meta, otadata=meta + NVS_SIZE,
                app=APP_BASE + i * APP_SIZE, fs=FS_BASE + i * FS_SIZE)


ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    print("wrote", rel)


def row(name, typ, sub, off, size):
    return f"{name:<10}{typ + ',':<6}{sub + ',':<9}0x{off:06X}, 0x{size:X}\n"


HDR = "# Name,   Type, SubType, Offset,   Size   (generated by tools/layout.py)\n"

menu = HDR
menu += row("nvs,", "data", "nvs", 0x9000, 0x5000)
menu += row("otadata,", "data", "ota", 0xE000, 0x2000)
menu += row("menu,", "app", "factory", MENU_APP_OFF, MENU_APP_SIZE)
menu += row("bootsel,", "data", "0x40", BOOTSEL_OFF, BOOTSEL_SIZE)
menu += row("ptables,", "data", "0x41", PTABLES_OFF, PTABLES_SIZE)
# Slot regions, sorted by offset (gen_esp32part requires ascending order).
# Declared as *data* so the stock bootloader can never pick them with the menu table.
extra = []
for i in range(n):
    s = slot(i)
    extra.append((s["nvs"], f"meta{i},", "0x44", NVS_SIZE + OTADATA_SIZE))
    extra.append((s["app"], f"img{i},", "0x42", APP_SIZE))
    extra.append((s["fs"], f"fs{i},", "0x43", FS_SIZE))
for off, name, sub, size in sorted(extra):
    menu += row(name, "data", sub, off, size)
write("partitions/menu.csv", menu)

for i, (name, fs_label, fs_size) in enumerate(SLOTS):
    s = slot(i)
    assert fs_size is None or fs_size <= FS_SIZE
    t = HDR.replace("(generated", f"[{name}] (generated")
    t += row("nvs,", "data", "nvs", s["nvs"], NVS_SIZE)
    t += row("otadata,", "data", "ota", s["otadata"], OTADATA_SIZE)
    t += row("app0,", "app", "ota_0", s["app"], APP_SIZE)
    t += row(f"{fs_label},", "data", "spiffs", s["fs"], fs_size or FS_SIZE)
    write(f"partitions/slot{i}.csv", t)

h = ["// Generated by tools/layout.py - do not edit by hand.",
     "#pragma once", "#include <stdint.h>", "",
     f"#define MB_SLOT_COUNT      {n}",
     f"#define MB_BOOTSEL_OFFSET  0x{BOOTSEL_OFF:06X}",
     f"#define MB_PTABLES_OFFSET  0x{PTABLES_OFF:06X}   // sector 0 = menu, sector i+1 = slot i",
     f"#define MB_PTABLE_ACTIVE   0x008000",
     f"#define MB_APP_SIZE        0x{APP_SIZE:06X}",
     "#define MB_MENU_INDEX      (-1)",
     "",
     "#define MB_MAGIC    0x4D42534Cu   // 'MBSL'",
     "#define MB_PENDING  0xFFFFFFFFu   // still erased = one-shot boot request not consumed",
     "#define MB_WAKE_MENU 0x4D454E55u  // 'MENU': set by Power Off, cleared (->0) by the bootloader",
     "",
     "typedef struct {",
     "    uint32_t magic;",
     "    uint32_t slot;      // last firmware chosen in the menu",
     "    uint32_t check;     // ~(magic ^ slot)",
     "    uint32_t pending;   // MB_PENDING: boot `slot` once; bootloader writes 0 (no erase needed)",
     "    uint32_t wake_menu; // MB_WAKE_MENU: next wake-up (after Power Off) goes to the menu",
     "} mb_record_t;", "",
     "static const char *const MB_SLOT_NAMES[MB_SLOT_COUNT] = {",
     *[f'    "{name[:14]}",' for name, _, _ in SLOTS],
     "};",
     "static const uint32_t MB_SLOT_APP_OFFSET[MB_SLOT_COUNT] = {",
     *[f"    0x{slot(i)['app']:06X}," for i in range(n)],
     "};", ""]
write("common/multiboot_layout.h", "\n".join(h))

with open(os.path.join(ROOT, "partitions", "layout.env"), "w") as f:
    f.write(f"SLOTS={n}\nPTABLES_OFF=0x{PTABLES_OFF:X}\nBOOTSEL_OFF=0x{BOOTSEL_OFF:X}\n")
    for i in range(n):
        s = slot(i)
        f.write(f"SLOT{i}_APP=0x{s['app']:X}\nSLOT{i}_FS=0x{s['fs']:X}\nSLOT{i}_META=0x{s['nvs']:X}\n")
    f.write(f"APP_SIZE=0x{APP_SIZE:X}\nFS_SIZE=0x{FS_SIZE:X}\nMETA_SIZE=0x{NVS_SIZE + OTADATA_SIZE:X}\n")
print(f"{n} slots, app {APP_SIZE // 1024} KB, fs {FS_SIZE // 1024} KB each")
